export function searchRTOs(query: string, stateFilter: string): RTO[] {
  const q = query.toLowerCase().trim();
  return rtoData.filter((rto) => {
    const matchesState = !stateFilter || stateFilter === "All States" || rto.state === stateFilter;
    const matchesQuery =
      !q ||
      rto.city.toLowerCase().includes(q) ||
      rto.name.toLowerCase().includes(q) ||
      rto.code.toLowerCase().includes(q) ||
      rto.state.toLowerCase().includes(q) ||
      rto.address.toLowerCase().includes(q);
    return matchesState && matchesQuery;
  });
}